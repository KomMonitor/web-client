import { TestBed } from '@angular/core/testing';
import { TranslateModule } from '@ngx-translate/core';

import { KommonitorIndicatorDataGridHelperService } from './kommonitor-data-grid-helper.service';
import { HtmlCellRendererComponent } from 'components/ngComponents/admin/adminShared/htmlCellRenderer/html-cell-renderer.component';
import { AccessControlService } from 'services/access-control-service/access-control.service';
import { EnvConfigService } from 'services/env-config-service/env-config.service';
import { MetadataExportService } from 'services/metadata-export-service/metadata-export.service';
import { TopicMetadataStoreService } from 'services/topic-metadata-store-service/topic-metadata-store.service';
import {
  HOSTILE_PAYLOAD,
  expectNoMarkupInjection,
  renderCellLikeAgGrid,
} from 'testing/ag-grid-cell.testing';

/**
 * An indicator with the hostile payload in every free-text field. Ids stay
 * plain: they are generated by the server, and the edit-buttons column still
 * builds its markup from them.
 */
function hostileIndicator(): any {
  return {
    indicatorId: 'indicator-1',
    indicatorName: HOSTILE_PAYLOAD,
    unit: HOSTILE_PAYLOAD,
    abbreviation: HOSTILE_PAYLOAD,
    characteristicValue: HOSTILE_PAYLOAD,
    creationType: HOSTILE_PAYLOAD,
    tags: [HOSTILE_PAYLOAD],
    indicatorType: 'STATUS_ABSOLUTE',
    isHeadlineIndicator: false,
    metadata: {
      description: HOSTILE_PAYLOAD,
      datasource: HOSTILE_PAYLOAD,
      contact: HOSTILE_PAYLOAD,
    },
    processDescription: 'Sum $$a+b$$ of all ' + HOSTILE_PAYLOAD,
    applicableSpatialUnits: [{ spatialUnitId: 'su-1', spatialUnitName: HOSTILE_PAYLOAD }],
    applicableDates: ['2024-01-01', HOSTILE_PAYLOAD],
    topicReference: 'sub-topic',
    permissions: ['permission-1'],
    isPublic: true,
    ownerId: 'owner-1',
    precision: 2,
    userPermissions: ['viewer', 'editor', 'creator'],
  };
}

describe('KommonitorIndicatorDataGridHelperService', () => {
  let service: KommonitorIndicatorDataGridHelperService;

  beforeEach(() => {
    TestBed.configureTestingModule({
      imports: [TranslateModule.forRoot()],
      providers: [
        {
          provide: AccessControlService,
          useValue: {
            // Group names are free text that group admins choose.
            getAllowedRolesString: () => HOSTILE_PAYLOAD,
            getRoleTitle: () => HOSTILE_PAYLOAD,
            checkDeletePermission: () => true,
          },
        },
        {
          provide: MetadataExportService,
          useValue: { getIndicatorStringFromIndicatorType: () => HOSTILE_PAYLOAD },
        },
        {
          provide: TopicMetadataStoreService,
          useValue: {
            availableTopics: [
              {
                topicId: 'main-topic',
                topicName: HOSTILE_PAYLOAD,
                subTopics: [{ topicId: 'sub-topic', topicName: 'Sub topic', subTopics: [] }],
              },
            ],
          },
        },
        { provide: EnvConfigService, useValue: { enableKeycloakSecurity: true } },
      ],
    });
    service = TestBed.inject(KommonitorIndicatorDataGridHelperService);
  });

  it('renders free text from the API as text in every column', () => {
    const indicator = hostileIndicator();
    const { columnDefs } = service.buildDataGrid_indicators([indicator]);

    const cells = expectNoMarkupInjection(columnDefs, indicator);

    // The payload is still shown — as text, not dropped.
    const textCells = cells.filter((cell) => cell.textContent?.includes(HOSTILE_PAYLOAD));
    expect(textCells.length).toBeGreaterThan(10);
  });

  it('renders the methodology through the sanitizing component without touching the row', () => {
    const indicator = hostileIndicator();
    const before = indicator.processDescription;
    const { columnDefs } = service.buildDataGrid_indicators([indicator]);
    const methodology = columnDefs.find((col) => col.cellRenderer === HtmlCellRendererComponent)!;

    expect(methodology).toBeDefined();
    expect(methodology.valueGetter).toEqual(expect.any(Function));
    expect((methodology.valueGetter as any)({ data: indicator })).toBe(before);

    // Rendering the other cells — repeatedly, as paging and sorting do — must
    // not append to the stored text either (D15).
    for (let i = 0; i < 3; i++) {
      columnDefs.forEach((col) => renderCellLikeAgGrid(col, indicator));
    }
    expect(indicator.processDescription).toBe(before);
  });

  it('lists the topic path one level per line', () => {
    const indicator = hostileIndicator();
    const { columnDefs } = service.buildDataGrid_indicators([indicator]);
    const topics = columnDefs.find((col) => col.headerName === 'ADMIN_SHARED_UI.TOPICS.TITLE')!;

    const cell = renderCellLikeAgGrid(topics, indicator)!;

    expect(Array.from(cell.children).map((line) => line.textContent)).toEqual([
      HOSTILE_PAYLOAD,
      'Sub topic',
    ]);
    expect(topics.filterValueGetter).toEqual(expect.any(Function));
    expect((topics.filterValueGetter as any)({ data: indicator })).toBe(
      `${HOSTILE_PAYLOAD} Sub topic`
    );
  });

  it('lists the spatial unit names as list items', () => {
    const indicator = hostileIndicator();
    const { columnDefs } = service.buildDataGrid_indicators([indicator]);
    const spatialUnits = columnDefs.find((col) => col.field === 'applicableSpatialUnits')!;

    const cell = renderCellLikeAgGrid(spatialUnits, indicator)!;

    expect(cell.tagName).toBe('UL');
    expect(Array.from(cell.querySelectorAll('li')).map((li) => li.textContent)).toEqual([
      HOSTILE_PAYLOAD,
    ]);
  });
});
